import numpy as np
import yfinance as yf
import pandas as pd
from scipy.optimize import minimize

# =============================================
# SECTION 1: STOCK RETURNS DATA INPUT
# =============================================

# Asset names (9 Nifty stocks + Gold)
assets = [
    'TITAN.NS', 'TATASTEEL.NS', 'SBIN.NS', 'NTPC.NS', 'COALINDIA.NS',
    'JSWSTEEL.NS', 'AXISBANK.NS', 'RELIANCE.NS', 'HINDALCO.NS',
    'GC=F'  # Gold futures ticker on yfinance
]

# Asset display names (for clean output)
asset_names = [
    'Titan', 'Tata Steel', 'SBIN', 'NTPC', 'Coal India',
    'JSW Steel', 'Axis Bank', 'Reliance', 'HINDALCO', 'Tata Gold ETF'
]

# Expected annual returns (values in decimals)
expected_returns = np.array([
    0.42,  # Titan
    0.33,  # Tata Steel
    0.55,  # SBIN
    0.27,  # NTPC
    0.42,  # Coal India
    0.10,  # JSW Steel
    0.11,  # Axis Bank
    0.03,  # Reliance
    0.38,  # HINDALCO
    0.88   # Tata Gold ETF
])

# Annual standard deviations (values in decimals)
std_devs = np.array([
    0.19,  # Titan
    0.30,  # Tata Steel
    0.23,  # SBIN
    0.20,  # NTPC
    0.25,  # Coal India
    0.26,  # JSW Steel
    0.24,  # Axis Bank
    0.20,  # Reliance
    0.30,  # HINDALCO
    0.72   # Tata Gold ETF
])

# Target minimum portfolio return (as decimal)
target_return = 0.10

# Historical data date range for correlation
start_date = '2025-10-01'
end_date   = '2026-03-01'

# =============================================
# SECTION 2: DOWNLOAD PRICE DATA & CORRELATION
# =============================================

raw = yf.download(assets, start=start_date, end=end_date, auto_adjust=True)['Close']
raw.columns = asset_names

# Drop rows where any asset has missing data
raw.dropna(inplace=True)

# Daily returns
daily_returns = raw.pct_change().dropna()

# Correlation matrix from historical data
correlation_matrix = daily_returns.corr().values

print("\nCorrelation Matrix:")
corr_df = pd.DataFrame(correlation_matrix, index=asset_names, columns=asset_names)
print(corr_df.round(3))

# =============================================
# SECTION 3: COVARIANCE MATRIX
# =============================================

# Σ = D * Corr * D  where D = diag(std_devs)
D = np.diag(std_devs)
cov_matrix = D @ correlation_matrix @ D

print("\nCovariance Matrix (Σ) constructed from manual std devs + historical correlations.")

# =============================================
# SECTION 4: OBJECTIVE - Minimise w^T Σ w
# =============================================

def portfolio_variance(weights, cov_matrix):
    return weights.T @ cov_matrix @ weights

n = len(assets)

# =============================================
# SECTION 5: CONSTRAINTS & BOUNDS
# =============================================

constraints = [
    # Weights sum to 1
    {'type': 'eq', 'fun': lambda w: np.sum(w) - 1},

    # Portfolio return == target
    {'type': 'eq', 'fun': lambda w: np.dot(w, expected_returns) - target_return}
]

# No short selling: all weights >= 0
bounds = tuple((0, None) for _ in range(n))

# =============================================
# SECTION 6: OPTIMISATION
# =============================================

w0 = np.ones(n) / n  # Equal weight initial guess

result = minimize(
    portfolio_variance,
    w0,
    args=(cov_matrix,),
    method='SLSQP',
    bounds=bounds,
    constraints=constraints
)

# =============================================
# SECTION 7: RESULTS
# =============================================

if result.success:
    optimal_weights = result.x

    print("\n OPTIMAL PORTFOLIO WEIGHTS ")
    print(f"{'Asset':<20} {'Weight':>10} {'Allocation %':>15}")
    print("-" * 47)
    for i, name in enumerate(asset_names):
        print(f"{name:<20} {optimal_weights[i]:>10.4f} {optimal_weights[i]*100:>14.2f}%")
    print("-" * 47)
    print(f"{'Sum of Weights':<20} {np.sum(optimal_weights):>10.4f}")
    print(f"\nPortfolio Expected Return : {np.dot(optimal_weights, expected_returns)*100:.2f}%")
    print(f"Portfolio Std Deviation   : {np.sqrt(portfolio_variance(optimal_weights, cov_matrix))*100:.2f}%")
else:
    print("\nOptimisation failed:", result.message)
    print("Try lowering the target_return value.")